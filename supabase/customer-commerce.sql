-- Customer commerce tables and policies
alter table public.profiles add column if not exists marketing_preferences jsonb not null default '{}'::jsonb;
alter table public.admin_orders add column if not exists public_id text;
create unique index if not exists admin_orders_public_id_key
  on public.admin_orders (public_id)
  where public_id is not null;

create table if not exists public.customer_addresses (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  label text not null,
  address text not null,
  phone text,
  is_default boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.customer_addresses enable row level security;
drop policy if exists "Customers manage own addresses" on public.customer_addresses;
create policy "Customers manage own addresses" on public.customer_addresses
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

create table if not exists public.customer_wishlist (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  product_name text not null,
  created_at timestamptz not null default now(),
  unique(user_id, product_name)
);
alter table public.customer_wishlist enable row level security;
drop policy if exists "Customers manage own wishlist" on public.customer_wishlist;
create policy "Customers manage own wishlist" on public.customer_wishlist
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

create table if not exists public.customer_cart (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  product_name text not null,
  product_type text,
  price numeric(12,2) not null,
  image text,
  quantity integer not null default 1 check (quantity > 0),
  updated_at timestamptz not null default now(),
  unique(user_id, product_name)
);
alter table public.customer_cart enable row level security;
drop policy if exists "Customers manage own cart" on public.customer_cart;
create policy "Customers manage own cart" on public.customer_cart
  for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

create table if not exists public.customer_orders (
  id bigint generated by default as identity primary key,
  public_id text not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  customer_name text not null,
  customer_email text not null,
  phone text,
  shipping_address text not null,
  payment_method text not null,
  total numeric(12,2) not null,
  status text not null default 'Pending',
  created_at timestamptz not null default now()
);
alter table public.customer_orders enable row level security;
drop policy if exists "Customers read own orders" on public.customer_orders;
create policy "Customers read own orders" on public.customer_orders
  for select using (auth.uid() = user_id);
drop policy if exists "Customers create own orders" on public.customer_orders;
create policy "Customers create own orders" on public.customer_orders
  for insert with check (auth.uid() = user_id);
drop policy if exists "Admins manage customer orders" on public.customer_orders;
create policy "Admins manage customer orders" on public.customer_orders
  for all using (public.is_admin()) with check (public.is_admin());

create table if not exists public.customer_order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.customer_orders(id) on delete cascade,
  product_name text not null,
  product_type text,
  price numeric(12,2) not null,
  quantity integer not null default 1,
  image text,
  created_at timestamptz not null default now()
);
alter table public.customer_order_items enable row level security;
drop policy if exists "Customers read own order items" on public.customer_order_items;
create policy "Customers read own order items" on public.customer_order_items
  for select using (exists (
    select 1 from public.customer_orders o
    where o.id = order_id and o.user_id = auth.uid()
  )) ;
drop policy if exists "Customers create own order items" on public.customer_order_items;
create policy "Customers create own order items" on public.customer_order_items
  for insert with check (exists (
    select 1 from public.customer_orders o
    where o.id = order_id and o.user_id = auth.uid()
  )) ;
drop policy if exists "Admins manage customer order items" on public.customer_order_items;
create policy "Admins manage customer order items" on public.customer_order_items
  for all using (public.is_admin()) with check (public.is_admin());

create or replace function public.mirror_customer_order()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.admin_orders (public_id, customer_name, customer_email, amount, status, created_at)
  values (new.public_id, new.customer_name, new.customer_email, new.total::text, new.status, new.created_at);
  insert into public.admin_activity (actor_email, action)
  values (new.customer_email, 'New customer order ' || new.public_id);
  return new;
end;
$$;
drop trigger if exists on_customer_order_created on public.customer_orders;
create trigger on_customer_order_created after insert on public.customer_orders
for each row execute procedure public.mirror_customer_order();

