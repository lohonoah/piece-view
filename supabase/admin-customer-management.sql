-- Admin customer management and login/activity audit
alter table public.profiles add column if not exists phone text;
drop policy if exists "Admins can manage customer profiles" on public.profiles;
create policy "Admins can manage customer profiles" on public.profiles
  for update using (public.is_admin()) with check (public.is_admin());

create or replace function public.guard_profile_role_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.role is distinct from old.role and not public.is_admin() then
    raise exception 'Only administrators can change account roles';
  end if;
  return new;
end;
$$;

drop trigger if exists on_profile_role_change on public.profiles;
create trigger on_profile_role_change
before update on public.profiles
for each row execute procedure public.guard_profile_role_change();
alter table public.profiles add column if not exists last_sign_in_at timestamptz;

create table if not exists public.admin_customer_activity (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  actor_email text,
  action text not null,
  details text,
  created_at timestamptz not null default now()
);
alter table public.admin_customer_activity enable row level security;
drop policy if exists "Only admins read customer activity" on public.admin_customer_activity;
create policy "Only admins read customer activity" on public.admin_customer_activity
  for select using (public.is_admin());
drop policy if exists "Only admins insert customer activity" on public.admin_customer_activity;
create policy "Only admins insert customer activity" on public.admin_customer_activity
  for insert with check (public.is_admin());

create or replace function public.log_auth_customer_activity()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.admin_customer_activity (user_id, actor_email, action, details)
    values (new.id, new.email, 'Account created', 'Customer account registered');
  elsif tg_op = 'UPDATE' then
    if old.email_confirmed_at is null and new.email_confirmed_at is not null then
      insert into public.admin_customer_activity (user_id, actor_email, action, details)
      values (new.id, new.email, 'Email verified', 'Account email confirmation completed');
    end if;
    if new.last_sign_in_at is not null and (old.last_sign_in_at is null or new.last_sign_in_at <> old.last_sign_in_at) then
      insert into public.admin_customer_activity (user_id, actor_email, action, details)
      values (new.id, new.email, 'Signed in', 'Successful password sign-in');
    end if;
  end if;
  return new;
end;
$$;
drop trigger if exists on_auth_customer_activity on auth.users;
create trigger on_auth_customer_activity after insert or update on auth.users
for each row execute procedure public.log_auth_customer_activity();

create or replace function public.log_profile_change()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if tg_op = 'UPDATE' and (old.full_name is distinct from new.full_name or old.email is distinct from new.email or old.phone is distinct from new.phone) then
    insert into public.admin_customer_activity (user_id, actor_email, action, details)
    values (new.id, new.email, 'Profile updated', 'Customer profile information changed');
  end if;
  if tg_op = 'UPDATE' and (old.last_sign_in_at is distinct from new.last_sign_in_at) then
    insert into public.admin_customer_activity (user_id, actor_email, action, details)
    values (new.id, new.email, 'Signed in', 'Successful account sign-in');
  end if;
  return new;
end;
$$;
drop trigger if exists on_profile_customer_activity on public.profiles;
create trigger on_profile_customer_activity after update on public.profiles
for each row execute procedure public.log_profile_change();

insert into public.admin_customer_activity (user_id, actor_email, action, details)
select u.id, u.email, 'Account registered', 'Existing customer backfilled'
from auth.users u
where not exists (
  select 1
  from public.admin_customer_activity activity
  where activity.user_id = u.id
    and activity.action in ('Account created','Account registered')
);

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'profiles'
  ) then
    alter publication supabase_realtime add table public.profiles;
  end if;

  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'admin_customer_activity'
  ) then
    alter publication supabase_realtime add table public.admin_customer_activity;
  end if;
end;
$$;

create or replace function public.admin_list_customers()
returns table (
  id uuid,
  email text,
  full_name text,
  role text,
  phone text,
  created_at timestamptz,
  last_sign_in_at timestamptz
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'Administrator access required';
  end if;

  return query
  select p.id, p.email, p.full_name, p.role, p.phone, p.created_at, p.last_sign_in_at
  from public.profiles p
  order by p.created_at desc;
end;
$$;

create or replace function public.admin_list_customer_activity()
returns table (
  id bigint,
  user_id uuid,
  actor_email text,
  action text,
  details text,
  created_at timestamptz
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'Administrator access required';
  end if;

  return query
  select a.id, a.user_id, a.actor_email, a.action, a.details, a.created_at
  from public.admin_customer_activity a
  order by a.created_at desc
  limit 100;
end;
$$;

revoke all on function public.admin_list_customers() from public;
grant execute on function public.admin_list_customers() to authenticated;
revoke all on function public.admin_list_customer_activity() from public;
grant execute on function public.admin_list_customer_activity() to authenticated;
