-- Newsletter opt-in storage and admin-only subscriber list.

create table if not exists public.newsletter_subscribers (
  id bigint generated by default as identity primary key,
  email text not null,
  unsubscribe_token uuid not null default gen_random_uuid(),
  subscribed_at timestamptz not null default now(),
  unsubscribed_at timestamptz,
  source text not null default 'storefront',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint newsletter_subscribers_email_check
    check (email = lower(trim(email)) and email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$')
);

alter table public.newsletter_subscribers
  add column if not exists unsubscribe_token uuid not null default gen_random_uuid();

create unique index if not exists newsletter_subscribers_email_lower_key
  on public.newsletter_subscribers (lower(email));
create unique index if not exists newsletter_subscribers_unsubscribe_token_key
  on public.newsletter_subscribers (unsubscribe_token);

alter table public.newsletter_subscribers enable row level security;
revoke all on public.newsletter_subscribers from public, anon, authenticated;

create or replace function public.subscribe_to_newsletter(p_email text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email text := lower(trim(p_email));
begin
  if v_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then
    raise exception 'Enter a valid email address';
  end if;

  insert into public.newsletter_subscribers (email)
  values (v_email)
  on conflict (lower(email)) do update
    set subscribed_at = now(),
        unsubscribed_at = null,
        unsubscribe_token = gen_random_uuid(),
        source = 'storefront',
        updated_at = now();
end;
$$;

revoke all on function public.subscribe_to_newsletter(text) from public;
grant execute on function public.subscribe_to_newsletter(text) to anon, authenticated;

create or replace function public.admin_list_newsletter_subscribers()
returns table (email text, subscribed_at timestamptz, source text)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'Administrator access required';
  end if;

  return query
    select subscriber.email, subscriber.subscribed_at, subscriber.source
    from public.newsletter_subscribers as subscriber
    where subscriber.unsubscribed_at is null
    order by subscriber.subscribed_at desc;
end;
$$;

revoke all on function public.admin_list_newsletter_subscribers() from public;
grant execute on function public.admin_list_newsletter_subscribers() to authenticated;
