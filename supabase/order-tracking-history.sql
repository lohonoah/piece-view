-- Keep a durable, customer-readable timeline for order status changes.

create table if not exists public.customer_order_status_history (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.customer_orders(id) on delete cascade,
  status text not null,
  note text not null,
  created_at timestamptz not null default now()
);

create index if not exists customer_order_status_history_order_created_idx
  on public.customer_order_status_history (order_id, created_at);

alter table public.customer_order_status_history enable row level security;
revoke all on public.customer_order_status_history from public, anon, authenticated;
grant select on public.customer_order_status_history to authenticated;

drop policy if exists "Customers read own order timeline" on public.customer_order_status_history;
create policy "Customers read own order timeline" on public.customer_order_status_history
  for select to authenticated using (
    exists (
      select 1 from public.customer_orders as customer_order
      where customer_order.id = order_id and customer_order.user_id = auth.uid()
    )
  );

drop policy if exists "Admins read order timelines" on public.customer_order_status_history;
create policy "Admins read order timelines" on public.customer_order_status_history
  for select to authenticated using (public.is_admin());

create or replace function public.record_customer_order_status_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.customer_order_status_history (order_id, status, note, created_at)
    values (new.id, new.status, 'Order received', new.created_at);
  elsif new.status is distinct from old.status then
    insert into public.customer_order_status_history (order_id, status, note)
    values (new.id, new.status, 'Order status updated to ' || new.status);
  end if;
  return new;
end;
$$;

drop trigger if exists customer_order_status_history_trigger on public.customer_orders;
create trigger customer_order_status_history_trigger
  after insert or update of status on public.customer_orders
  for each row execute function public.record_customer_order_status_change();

insert into public.customer_order_status_history (order_id, status, note, created_at)
select customer_order.id, customer_order.status, 'Current status when tracking history began', customer_order.created_at
from public.customer_orders as customer_order
where not exists (
  select 1 from public.customer_order_status_history as history
  where history.order_id = customer_order.id
);

create or replace function public.get_customer_order_tracking(p_public_id text)
returns table (status text, note text, created_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  return query
    select history.status, history.note, history.created_at
    from public.customer_order_status_history as history
    join public.customer_orders as customer_order on customer_order.id = history.order_id
    where customer_order.public_id = p_public_id
      and customer_order.user_id = auth.uid()
    order by history.created_at, history.id;
end;
$$;

revoke all on function public.get_customer_order_tracking(text) from public;
grant execute on function public.get_customer_order_tracking(text) to authenticated;
