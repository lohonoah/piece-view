create table if not exists public.customer_order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.customer_orders(id) on delete cascade,
  product_name text not null,
  product_type text,
  price numeric(12,2) not null,
  quantity integer not null default 1,
  image text,
  created_at timestamptz not null default now()
);
alter table public.customer_order_items enable row level security;
create policy "Customers read own order items" on public.customer_order_items
  for select using (exists (
    select 1 from public.customer_orders o
    where o.id = order_id and o.user_id = auth.uid()
  ));
create policy "Customers create own order items" on public.customer_order_items
  for insert with check (exists (
    select 1 from public.customer_orders o
    where o.id = order_id and o.user_id = auth.uid()
  ));
create policy "Admins manage customer order items" on public.customer_order_items
  for all using (public.is_admin()) with check (public.is_admin());

create or replace function public.mirror_customer_order()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.admin_orders (customer_name, customer_email, amount, status, created_at)
  values (new.customer_name, new.customer_email, new.total::text, new.status, new.created_at)
  on conflict do nothing;
  insert into public.admin_activity (actor_email, action)
  values (new.customer_email, 'New customer order ' || new.public_id);
  return new;
end;
$$;
drop trigger if exists on_customer_order_created on public.customer_orders;
create trigger on_customer_order_created after insert on public.customer_orders
for each row execute procedure public.mirror_customer_order();
