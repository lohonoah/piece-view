create table if not exists public.admin_notes (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  body text not null,
  created_at timestamptz not null default now()
);

alter table public.admin_notes enable row level security;
create policy "Only admins can read admin notes"
  on public.admin_notes for select
  using (public.is_admin());
create policy "Only admins can insert admin notes"
  on public.admin_notes for insert
  with check (public.is_admin() and owner_id = auth.uid());
create policy "Only admins can update own admin notes"
  on public.admin_notes for update
  using (public.is_admin() and owner_id = auth.uid())
  with check (public.is_admin() and owner_id = auth.uid());
create policy "Only admins can delete own admin notes"
  on public.admin_notes for delete
  using (public.is_admin() and owner_id = auth.uid());

